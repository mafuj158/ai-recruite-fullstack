export function getConversationsByRole(role: "candidate" | "employer"): ChatConversation[] {
  return role === "candidate" ? MOCK_CANDIDATE_CONVERSATIONS : MOCK_EMPLOYER_CONVERSATIONS;
}

export function getConversationById(
  id: string,
  role: "candidate" | "employer"
): ChatConversation | undefined {
  const list = getConversationsByRole(role);
  return list.find((c) => c.id === id) || list[0];
}
